"""Generate a self-contained proxy up project from a service XRD.

The only input is the XRD. Everything the proxy needs is derived from it at
build time: the composite type, the ProxyConfig name (the XRD name), the
remote-name prefix and the `*SecretRef` fields to forward. The generic proxy
function is vendored into the project with those constants in config.py.
"""

import pathlib
import pprint
import shutil
import urllib.request

import yaml

HERE = pathlib.Path(__file__).resolve().parent
FUNCTION_SRC = HERE.parent / "proxy_function"
FUNCTION_NAME = "proxy"
PREFIX_MAX = 20


def read_source(src: str) -> bytes:
    """Read an XRD from a path or an http(s) URL, byte for byte."""
    if src.startswith(("http://", "https://")):
        with urllib.request.urlopen(src) as r:
            return r.read()
    return pathlib.Path(src).read_bytes()


def to_dns_label(s: str) -> str:
    """Port of up's xpkg.ToDNSLabel, which names embedded function packages."""
    out = []
    for i, ch in enumerate(s):
        if ch.isascii() and (ch.islower() or ch.isdigit()):
            out.append(ch)
        if ch in "./:-" and i not in (0, 62, len(s) - 1):
            out.append("-")
        if i == 62:
            break
    return "".join(out).strip("-")


def function_ref(repository: str) -> str:
    """The Function name up gives the embedded proxy function."""
    parts = repository.split("/")
    if len(parts) > 1 and ("." in parts[0] or ":" in parts[0]):
        parts = parts[1:]
    return to_dns_label("/".join(parts) + "_" + FUNCTION_NAME)


def secret_ref_paths(schema: dict, path: tuple = ()) -> list[list[str]]:
    """Find `*SecretRef` objects with a `name`, by the Crossplane convention."""
    found = []
    for prop, sub in (schema.get("properties") or {}).items():
        here = (*path, prop)
        if prop.endswith("SecretRef") and "name" in (sub.get("properties") or {}):
            found.append(list(here))
            continue
        if sub.get("type") == "object":
            found.extend(secret_ref_paths(sub, here))
    return found


def describe(xrd: dict) -> dict:
    """Pull out what the proxy needs to know about an XRD."""
    spec = xrd["spec"]
    versions = spec["versions"]
    ref = next((v for v in versions if v.get("referenceable")), versions[0])
    paths = []
    for v in versions:
        root = v.get("schema", {}).get("openAPIV3Schema", {})
        for p in secret_ref_paths(root):
            if p not in paths:
                paths.append(p)
    kind = spec["names"]["kind"]
    return {
        "xrdName": xrd["metadata"]["name"],
        "group": spec["group"],
        "kind": kind,
        "plural": spec["names"]["plural"],
        "version": ref["name"],
        "proxyConfigName": xrd["metadata"]["name"],
        "namePrefix": kind.lower()[:PREFIX_MAX],
        "secretRefPaths": paths,
    }


def render_config(infos: list[dict]) -> str:
    """Render the generated config.py."""
    proxies = {
        f"{i['group']}/{i['kind']}": {
            "proxyConfigName": i["proxyConfigName"],
            "namePrefix": i["namePrefix"],
            "secretRefPaths": i["secretRefPaths"],
        }
        for i in infos
    }
    return (
        '"""Generated by soc_proxy_gen from the service XRD. Do not edit."""\n\n'
        f"PROXIES: dict[str, dict] = {pprint.pformat(proxies, width=100, sort_dicts=True)}\n"
    )


def project(name: str, repository: str, infos: list[dict], deps: dict, source: str) -> dict:
    """The generated upbound.yaml."""
    apis = ", ".join(i["xrdName"] for i in infos)
    return {
        "apiVersion": "meta.dev.upbound.io/v2alpha1",
        "kind": "Project",
        "metadata": {"name": name},
        "spec": {
            "repository": repository,
            "description": f"Generated proxy for {apis} (source: {source}). Do not edit.",
            "license": "Apache-2.0",
            "maintainer": "Upbound <support@upbound.io>",
            "crossplane": {"version": ">=v2.0.0-0"},
            "dependsOn": [
                {
                    "apiVersion": "pkg.crossplane.io/v1",
                    "kind": "Provider",
                    "package": deps["providerKubernetes"],
                    "version": deps["providerKubernetesVersion"],
                },
                *([{
                    "apiVersion": "pkg.crossplane.io/v1",
                    "kind": "Configuration",
                    "package": deps["proxyBase"],
                    "version": deps["proxyBaseVersion"],
                }] if deps.get("proxyBase") else []),
            ],
        },
    }


def composition(info: dict, fn_ref: str) -> dict:
    """The generated proxy Composition: one step, the vendored function."""
    return {
        "apiVersion": "apiextensions.crossplane.io/v1",
        "kind": "Composition",
        "metadata": {"name": info["xrdName"]},
        "spec": {
            "compositeTypeRef": {"apiVersion": f"{info['group']}/{info['version']}", "kind": info["kind"]},
            "mode": "Pipeline",
            "pipeline": [{"step": "proxy", "functionRef": {"name": fn_ref}}],
        },
    }


def generate(
    xrds: list[str], out: pathlib.Path, name: str, repository: str, deps: dict, examples: list[str] | None = None
) -> list[dict]:
    """Write the proxy project to `out`, replacing anything there."""
    if out.exists():
        shutil.rmtree(out)
    infos = []
    for src in xrds:
        raw = read_source(src)
        info = describe(yaml.safe_load(raw))
        info["source"] = src
        apis = out / "apis" / info["plural"]
        apis.mkdir(parents=True)
        (apis / "definition.yaml").write_bytes(raw)
        infos.append(info)

    fn_ref = function_ref(repository)
    for info in infos:
        comp = out / "apis" / info["plural"] / "composition.yaml"
        comp.write_text(yaml.safe_dump(composition(info, fn_ref), sort_keys=False))

    fn_dir = out / "functions" / FUNCTION_NAME
    shutil.copytree(FUNCTION_SRC, fn_dir, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    (fn_dir / "function" / "config.py").write_text(render_config(infos))

    sources = ", ".join(i["source"] for i in infos)
    (out / "upbound.yaml").write_text(
        yaml.safe_dump(project(name, repository, infos, deps, sources), sort_keys=False))

    for ex in examples or []:
        doc = yaml.safe_load(read_source(ex))
        match = next(i for i in infos if i["kind"] == doc["kind"])
        dst = out / "examples" / match["plural"]
        dst.mkdir(parents=True, exist_ok=True)
        rel = dst / pathlib.Path(ex).name
        rel.write_bytes(read_source(ex))
        xrd = yaml.safe_load((out / "apis" / match["plural"] / "definition.yaml").read_bytes())
        tdir = out / "tests" / f"test-proxy-{match['plural']}"
        tdir.mkdir(parents=True, exist_ok=True)
        (tdir / "test.yaml").write_text(
            yaml.safe_dump_all(render_tests(match, xrd, doc, rel.relative_to(out)), sort_keys=False))

    return infos


TEST_PC = {"kind": "ClusterProviderConfig", "name": "test-service-cp"}
TEST_NS = "ctp-test"


def status_fixture(xrd: dict, version: str) -> dict:
    """A status value for every top-level string or string-list status field."""
    v = next(x for x in xrd["spec"]["versions"] if x["name"] == version)
    props = v.get("schema", {}).get("openAPIV3Schema", {}).get("properties", {})
    out = {}
    for name, sub in (props.get("status", {}).get("properties") or {}).items():
        if sub.get("type") == "string":
            out[name] = f"test-{name}"
        elif sub.get("type") == "array" and (sub.get("items") or {}).get("type") == "string":
            out[name] = [f"test-{name}"]
    return out


def render_tests(info: dict, xrd: dict, xr: dict, xr_path: pathlib.Path) -> list[dict]:
    """Smoke tests that the generated proxy renders: create, and read back."""
    import hashlib

    meta = xr["metadata"]
    rname = f"{info['namePrefix']}-" + hashlib.sha256(
        f"{meta['namespace']}/{meta['name']}".encode()).hexdigest()[:10]
    base = {
        "compositionPath": f"apis/{info['plural']}/composition.yaml",
        "xrdPath": f"apis/{info['plural']}/definition.yaml",
        "xrPath": str(xr_path),
        "timeoutSeconds": 120,
        "validate": False,
        "extraResources": [{
            "apiVersion": "soc.upbound.io/v1alpha1",
            "kind": "ProxyConfig",
            "metadata": {"name": info["proxyConfigName"]},
            "spec": {"providerConfigRef": TEST_PC, "remoteNamespace": TEST_NS},
        }],
    }
    remote = {
        "apiVersion": "kubernetes.m.crossplane.io/v1alpha1",
        "kind": "Object",
        "metadata": {"name": rname, "namespace": meta["namespace"]},
        "spec": {
            "providerConfigRef": TEST_PC,
            "readiness": {"policy": "DeriveFromObject"},
            "forProvider": {"manifest": {
                "apiVersion": xr["apiVersion"],
                "kind": xr["kind"],
                "metadata": {
                    "name": rname,
                    "namespace": TEST_NS,
                    "labels": {
                        "soc.upbound.io/origin-namespace": meta["namespace"],
                        "soc.upbound.io/origin-name": meta["name"],
                    },
                },
            }},
        },
    }
    status = status_fixture(xrd, info["version"])
    observed = {
        "apiVersion": "kubernetes.m.crossplane.io/v1alpha1",
        "kind": "Object",
        "metadata": {
            "name": rname,
            "namespace": meta["namespace"],
            "annotations": {"crossplane.io/composition-resource-name": "remote"},
        },
        "spec": {"forProvider": {"manifest": remote["spec"]["forProvider"]["manifest"]}},
        "status": {
            "conditions": [
                {"type": "Ready", "status": "True", "reason": "Available",
                 "lastTransitionTime": "2026-01-01T00:00:00Z"},
                {"type": "Synced", "status": "True", "reason": "ReconcileSuccess",
                 "lastTransitionTime": "2026-01-01T00:00:00Z"},
            ],
            "atProvider": {"manifest": {
                **remote["spec"]["forProvider"]["manifest"],
                "status": {**status, "conditions": [
                    {"type": "Ready", "status": "True", "reason": "Available",
                     "lastTransitionTime": "2026-01-01T00:00:00Z"}]},
            }},
        },
    }
    return [
        {
            "apiVersion": "meta.dev.upbound.io/v1alpha1",
            "kind": "CompositionTest",
            "metadata": {"name": f"{info['plural']}-creates-remote"},
            "spec": {**base, "assertResources": [remote]},
        },
        {
            "apiVersion": "meta.dev.upbound.io/v1alpha1",
            "kind": "CompositionTest",
            "metadata": {"name": f"{info['plural']}-reads-back-status"},
            "spec": {
                **base,
                "observedResources": [observed],
                "assertResources": [{
                    "apiVersion": xr["apiVersion"],
                    "kind": xr["kind"],
                    "metadata": {"name": meta["name"], "namespace": meta["namespace"]},
                    "status": status,
                }],
            },
        },
    ]


def check(xrds: list[str], out: pathlib.Path) -> list[str]:
    """Report every generated XRD that is not byte-identical to its source."""
    problems = []
    for src in xrds:
        raw = read_source(src)
        info = describe(yaml.safe_load(raw))
        dst = out / "apis" / info["plural"] / "definition.yaml"
        if not dst.exists():
            problems.append(f"{dst}: missing (source {src})")
        elif dst.read_bytes() != raw:
            problems.append(f"{dst}: differs from source {src}")
    return problems
